#!/usr/bin/env node
function parseCurl(cmd) {
  const urlMatch = cmd.match(/curl\s+(?:-X\s+([A-Z]+)\s+)?['"]?(https?:\/\/[^\s'"]+)['"]?/);
  const method = (cmd.match(/-X\s+([A-Z]+)/) || [])[1] || 'GET';
  const url = urlMatch ? urlMatch[2] : 'https://api.example.com';

  const headers = {};
  const headerMatches = cmd.matchAll(/-H\s+['"]([^:]+):\s*([^'"]+)['"]/g);
  for (const m of headerMatches) {
    headers[m[1].trim()] = m[2].trim();
  }

  let body = null;
  const dataMatch = cmd.match(/(?:-d|--data(?:-raw)?)\s+['"](.*?)['"](?=\s+-[a-zA-Z]|\s*$)/s);
  if (dataMatch) {
    try {
      body = JSON.parse(dataMatch[1]);
    } catch {
      body = dataMatch[1];
    }
  }

  return { method, url, headers, body };
}

function generateTypes(parsed, name = 'Request') {
  let ts = `// Auto-generated by curl-to-ts\n\n`;
  if (parsed.body && typeof parsed.body === 'object') {
    ts += `export interface ${name}Payload {\n`;
    for (const [k, v] of Object.entries(parsed.body)) {
      ts += `  ${k}: ${typeof v};\n`;
    }
    ts += `}\n\n`;
  }

  ts += `export async function execute${name}(payload?: any): Promise<Response> {\n`;
  ts += `  return fetch("${parsed.url}", {\n`;
  ts += `    method: "${parsed.method}",\n`;
  if (Object.keys(parsed.headers).length) {
    ts += `    headers: ${JSON.stringify(parsed.headers, null, 6)},\n`;
  }
  if (parsed.body) {
    ts += `    body: JSON.stringify(payload || ${JSON.stringify(parsed.body)})\n`;
  }
  ts += `  });\n`;
  ts += `}\n`;
  return ts;
}

function run() {
  const args = process.argv.slice(2);
  if (args.includes('--help') || args.includes('-h') || !args.length) {
    console.log('curl-to-ts - Generate TypeScript from cURL command');
    console.log('Usage: npx curl-to-ts "<curl command>" [options]');
    process.exit(0);
  }
  if (args.includes('--version') || args.includes('-v')) {
    console.log('curl-to-ts v1.0.0');
    process.exit(0);
  }

  const curlCmd = args[0];
  const parsed = parseCurl(curlCmd);
  const ts = generateTypes(parsed, 'Api');
  console.log(ts);
}

if (require.main === module) {
  run();
}

module.exports = { parseCurl, generateTypes, run };
